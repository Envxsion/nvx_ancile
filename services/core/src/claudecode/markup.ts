/**
 * ------------------------------------------------------------------
 *  Title    |  Claude Code's own markup in user entries
 *  Ref      |  docs/claude-code.md (How sessions look in a thread)
 *  ID       |  core
 * ------------------------------------------------------------------
 *  Purpose  |  Tell apart what the person typed from what Claude Code
 *           |  wrote into the user side of a transcript: slash
 *           |  commands and their output, background-task and
 *           |  cross-session notifications, agent hand-backs, the
 *           |  compaction summary, interruptions and system reminders.
 *  How      |  classifyUser() looks at one user entry's text (and its
 *           |  `origin`, when Claude Code recorded one) and answers
 *           |  what it is, with the fields map.ts puts in
 *           |  provenance.claude_code. Known wrapper tags live in one
 *           |  small table; a message made only of unknown wrapper
 *           |  tags is a notification from 'system'.
 *  Note     |  Measured on real sessions (Claude Code 2.1.x). Only
 *           |  the shape is relied on, never the wording, except the
 *           |  compaction and interruption sentences, which Claude
 *           |  Code writes verbatim.
 * ------------------------------------------------------------------
 */

export type NotificationSource = 'task' | 'session' | 'agent' | 'system';

/** provenance.claude_code.command: a slash command (or `!` shell command) the person ran. */
export interface CcCommand {
  /** "/model", or "!" for a shell command typed with `!`. */
  name: string;
  args: string;
  /** What the command printed (stdout, then stderr), ANSI codes removed; null when nothing. */
  output: string | null;
}

/** provenance.claude_code.notification: something Claude Code put in the conversation. */
export interface CcNotification {
  source: NotificationSource;
  title: string;
  from?: string;
  status?: string;
}

export type UserClass =
  | { kind: 'prompt'; text: string }
  | { kind: 'skip' }
  | { kind: 'compact'; text: string }
  | { kind: 'interrupted' }
  | { kind: 'command'; command: CcCommand }
  | { kind: 'command_output'; output: string | null }
  | { kind: 'notification'; notification: CcNotification; body: string };

const COMPACT_LEAD = 'This session is being continued from a previous conversation';
const CAVEAT_LEAD = 'Caveat: The messages below were generated by the user while running local commands';
const INTERRUPTED = /^\[Request interrupted by user[^\]]*\]$/;

// biome-ignore lint/suspicious/noControlCharactersInRegex: ANSI escape sequences are control characters.
const ANSI = /\u001b\[[0-9;?]*[ -/]*[@-~]|\u001b\][^\u0007\u001b]*(?:\u0007|\u001b\\)|\u001b[@-Z\\-_]/g;

export const stripAnsi = (s: string) => s.replace(ANSI, '');

/** Remove <system-reminder> blocks (Claude Code's notes to the model, never the person's words). */
export function stripReminders(s: string): string {
  return s.replace(/<system-reminder>[\s\S]*?<\/system-reminder>\s*/g, '');
}

export function isInterruption(s: string): boolean {
  return INTERRUPTED.test(s.trim());
}

/** The text inside the first <tag …>…</tag>, or null. */
function inner(s: string, tag: string): string | null {
  const m = new RegExp(`<${tag}(?:\\s[^>]*)?>([\\s\\S]*?)</${tag}>`).exec(s);
  return m ? (m[1] ?? '') : null;
}

/** An attribute of the first <tag …>, or null. */
function attr(s: string, tag: string, name: string): string | null {
  const open = new RegExp(`<${tag}(\\s[^>]*)?>`).exec(s)?.[1] ?? '';
  const m = new RegExp(`(?:^|\\s)${name}="([^"]*)"`).exec(open);
  return m ? (m[1] ?? '') : null;
}

/** Whole elements to leave out of a notification's body (ids, files, counters). */
const DROP = [
  'task-id',
  'tool-use-id',
  'output-file',
  'status',
  'summary',
  'usage',
  'worktree',
  'command-message',
];

/** Tags removed, inner text kept, blank runs collapsed: the body as markdown. */
export function bodyOf(s: string): string {
  let t = s;
  for (const tag of DROP) t = t.replace(new RegExp(`<${tag}(?:\\s[^>]*)?>[\\s\\S]*?</${tag}>`, 'g'), '');
  t = t
    .replace(/<[a-z][a-z0-9-]*(?:\s[^>]*)?\/>/g, '')
    .replace(/<\/?[a-z][a-z0-9-]*(?:\s[^>]*)?>/g, '')
    .replace(/\n{3,}/g, '\n\n');
  return t.trim();
}

const WRAPPER_ONLY = /^\s*(?:<([a-z][a-z0-9-]*)(?:\s[^>]*)?>[\s\S]*?<\/\1>\s*)+$/;
const FIRST_TAG = /^\s*<([a-z][a-z0-9-]*)/;
/** A known notification tag after a short one-line lead-in ("A message arrived: <…>"). */
const LEAD_IN = /^[^\n<]{0,200}:\s*<(task-notification|cross-session-message|agent-message)[\s>]/;

function oneLine(s: string, max = 120): string {
  const line = s.replace(/\s+/g, ' ').trim();
  return line.length > max ? `${line.slice(0, max - 3)}...` : line;
}

function taskNotification(s: string): { notification: CcNotification; body: string } {
  const summary = oneLine(inner(s, 'summary') ?? '');
  const status = (inner(s, 'status') ?? '').trim();
  const failed = /^(failed|error|errored)$/i.test(status);
  const stopped = /^(killed|stopped|cancell?ed|aborted)$/i.test(status);
  const lead = failed
    ? 'Background task failed'
    : stopped
      ? 'Background task stopped'
      : status
        ? 'Background task finished'
        : 'Background task';
  return {
    notification: {
      source: 'task',
      title: summary ? `${lead}: ${summary}` : lead,
      ...(status && { status }),
    },
    body: bodyOf(s.slice(s.indexOf('<task-notification'))),
  };
}

function wrapped(s: string, tag: string): { notification: CcNotification; body: string } {
  const at = s.indexOf(`<${tag}`);
  const from = at >= 0 ? s.slice(at) : s;
  if (tag === 'task-notification') return taskNotification(from);
  if (tag === 'cross-session-message') {
    const name = attr(from, tag, 'from-name') ?? attr(from, tag, 'from');
    return {
      notification: {
        source: 'session',
        title: name ? `Message from ${name}` : 'Message from another session',
        ...(name && { from: name }),
      },
      body: bodyOf(from),
    };
  }
  if (tag === 'agent-message') {
    const name = attr(from, tag, 'from-name') ?? attr(from, tag, 'from');
    return {
      notification: { source: 'agent', title: 'Report from an agent', ...(name && { from: name }) },
      body: bodyOf(from),
    };
  }
  return { notification: { source: 'system', title: 'Note from Claude Code' }, body: bodyOf(s) };
}

type Origin = { kind?: unknown; name?: unknown; body?: unknown; handback?: unknown };

/**
 * What a user entry is. `text` is its string content (or its text blocks
 * joined, when it has nothing else); `origin` is the entry's own field.
 */
export function classifyUser(text: string, origin?: unknown, meta = false): UserClass {
  const o = (origin && typeof origin === 'object' ? origin : {}) as Origin;
  const raw = stripReminders(text);
  const t = raw.trim();

  if (t.startsWith(COMPACT_LEAD)) return { kind: 'compact', text: t };

  if (o.kind === 'peer') {
    const name = typeof o.name === 'string' && o.name ? o.name : undefined;
    const body = bodyOf(typeof o.body === 'string' && o.body ? o.body : t);
    const notification: CcNotification =
      o.handback === true
        ? { source: 'agent', title: 'Report from an agent', ...(name && { from: name }) }
        : {
            source: 'session',
            title: name ? `Message from ${name}` : 'Message from another session',
            ...(name && { from: name }),
          };
    return { kind: 'notification', notification, body };
  }
  if (o.kind === 'task-notification') return { kind: 'notification', ...taskNotification(t) };

  // Other meta entries are Claude Code's own (skill text, injected context).
  if (meta) return { kind: 'skip' };
  if (!t) return text.trim() ? { kind: 'skip' } : { kind: 'prompt', text: '' };
  if (t.startsWith(CAVEAT_LEAD)) return { kind: 'skip' };
  if (isInterruption(t)) return { kind: 'interrupted' };

  const name = inner(t, 'command-name');
  if (name !== null && WRAPPER_ONLY.test(t)) {
    return {
      kind: 'command',
      command: { name: name.trim(), args: (inner(t, 'command-args') ?? '').trim(), output: null },
    };
  }
  const bash = inner(t, 'bash-input');
  if (bash !== null && WRAPPER_ONLY.test(t)) {
    return { kind: 'command', command: { name: '!', args: bash.trim(), output: null } };
  }
  const outTags = ['local-command-stdout', 'local-command-stderr', 'bash-stdout', 'bash-stderr'];
  const first = FIRST_TAG.exec(t)?.[1];
  if (first && outTags.includes(first) && WRAPPER_ONLY.test(t)) {
    const parts = outTags
      .map((tag) => inner(t, tag))
      .filter((x): x is string => x !== null)
      .map((x) => stripAnsi(x).trim())
      .filter(Boolean);
    return { kind: 'command_output', output: parts.length ? parts.join('\n') : null };
  }
  if (first && WRAPPER_ONLY.test(t)) return { kind: 'notification', ...wrapped(t, first) };
  const lead = LEAD_IN.exec(t)?.[1];
  if (lead) return { kind: 'notification', ...wrapped(t, lead) };
  return { kind: 'prompt', text: raw };
}

/** The line a command shows as: "/model opus", "! ls -la". */
export function commandLine(c: CcCommand): string {
  return c.args ? `${c.name} ${c.args}` : c.name;
}

export function joinOutput(a: string | null, b: string | null): string | null {
  if (a && b) return `${a}\n${b}`;
  return a ?? b ?? null;
}
