/**
 * Claude Code's own markup on the user side of a transcript, mapped to
 * what the Cockpit draws: commands, notifications, compaction,
 * interruptions, reminders. Fixtures follow the shapes measured on real
 * sessions (Claude Code 2.1.x); the words are made up.
 */
import type { Part } from '@nvx/contracts';
import { describe, expect, it } from 'vitest';
import type { CcSessionMessage } from '../../src/claudecode/bridge-protocol';
import { classify, type MirrorState, type PlannedMessage, planSync } from '../../src/claudecode/map';
import { bodyOf, classifyUser, stripAnsi } from '../../src/claudecode/markup';
import { assistant, toolResult, user } from './fake-bridge';

const empty = (): MirrorState => ({ byUuid: new Map(), messages: new Map() });
const plan = (chain: CcSessionMessage[], mirror = empty()) => {
  let n = 0;
  return planSync(chain, mirror, () => `m${n++}`, null);
};
const text = (parts: Part[]) => parts.flatMap((p) => (p.type === 'text' ? [p.text] : [])).join('');
/** A mirror as the store would build it from planned messages. */
function mirrorOf(planned: PlannedMessage[]): MirrorState {
  const m = empty();
  const parents = new Set(planned.map((p) => p.parent_id));
  for (const p of planned) {
    for (const u of p.uuids) m.byUuid.set(u, p.id);
    m.messages.set(p.id, {
      role: p.role,
      lastUuid: p.uuids.at(-1) ?? '',
      hasChildren: parents.has(p.id),
      lastApiId: p.last_api_id,
      kind: p.kind,
    });
  }
  return m;
}

const COMMAND =
  '<command-name>/model</command-name>\n            <command-message>model</command-message>\n            <command-args>opus</command-args>';
const STDOUT = '<local-command-stdout>Set model to \u001b[1mOpus 5.5\u001b[22m</local-command-stdout>';
const TASK = `<task-notification>
<task-id>b1x9</task-id>
<tool-use-id>toolu_01</tool-use-id>
<output-file>C:\\Temp\\tasks\\b1x9.output</output-file>
<status>completed</status>
<summary>Agent "Find the docs" completed</summary>
<note>Read the output file for the full log.</note>
<result>Found **three** places:

- docs/a.md
- docs/b.md</result>
<usage><total_tokens>1200</total_tokens><tool_uses>4</tool_uses></usage>
<subagent id="ag1" />
</task-notification>`;
const CROSS =
  '<cross-session-message from="C:\\\\Code\\\\nvx_folio" from-name="nvx_folio" from-mode="prompting">\nThe build is green on my side.\n</cross-session-message>';

describe('slash commands', () => {
  it('makes one user message of kind command, with its output folded in', () => {
    const { planned } = plan([user('c1', COMMAND), user('c2', STDOUT), user('u1', 'Thanks')]);
    expect(planned).toHaveLength(2);
    const [cmd, next] = planned;
    expect(cmd).toMatchObject({
      role: 'user',
      kind: 'command',
      command: { name: '/model', args: 'opus', output: 'Set model to Opus 5.5' },
      parts: [{ type: 'text', text: '/model opus' }],
      uuids: ['c1', 'c2'],
    });
    expect(next?.parent_id).toBe(cmd?.id);
  });

  it('folds output that arrives in a later sync into the command already mirrored', () => {
    const first = plan([user('c1', COMMAND)]);
    const mirror = mirrorOf(first.planned);
    const { planned } = plan([user('c1', COMMAND), user('c2', STDOUT)], mirror);
    expect(planned).toEqual([
      expect.objectContaining({
        extends: true,
        id: first.planned[0]?.id,
        output: 'Set model to Opus 5.5',
        uuids: ['c2'],
      }),
    ]);
  });

  it('reads a `!` shell command and its stdout and stderr', () => {
    const { planned } = plan([
      user('b1', '<bash-input>git status</bash-input>'),
      user('b2', '<bash-stdout>On branch main</bash-stdout><bash-stderr></bash-stderr>'),
    ]);
    expect(planned).toHaveLength(1);
    expect(planned[0]).toMatchObject({
      kind: 'command',
      command: { name: '!', args: 'git status', output: 'On branch main' },
      parts: [{ type: 'text', text: '! git status' }],
    });
  });

  it('drops the caveat Claude Code writes before local commands', () => {
    const caveat =
      'Caveat: The messages below were generated by the user while running local commands. DO NOT respond to these messages.';
    const { planned } = plan([
      user('a', 'Hello'),
      user('cv', caveat, { is_meta: true }),
      user('c1', COMMAND),
    ]);
    expect(planned.map((p) => p.kind)).toEqual([null, 'command']);
    // Not marked meta, it is still dropped.
    expect(classify(user('cv2', caveat)).kind).toBe('skip');
  });

  it('shows output with no command before it as a note', () => {
    const { planned } = plan([user('x', STDOUT)]);
    expect(planned[0]).toMatchObject({
      role: 'system',
      kind: 'notification',
      notification: { source: 'system', title: 'Command output' },
    });
  });
});

describe('notifications', () => {
  it('turns a background task notification into a system message with its result as the body', () => {
    const { planned } = plan([user('t1', TASK, { origin: { kind: 'task-notification' } } as never)]);
    const n = planned[0];
    expect(n).toMatchObject({
      role: 'system',
      kind: 'notification',
      notification: {
        source: 'task',
        title: 'Background task finished: Agent "Find the docs" completed',
        status: 'completed',
      },
    });
    const body = text(n?.parts ?? []);
    expect(body).toContain('Found **three** places:');
    expect(body).toContain('- docs/b.md');
    expect(body).not.toMatch(/<|task-id|b1x9|toolu_01|1200/);
  });

  it('recognises a task notification without an origin, and a failed one', () => {
    const failed = TASK.replace('completed</status>', 'failed</status>');
    expect(classify(user('t', failed))).toMatchObject({
      kind: 'notification',
      notification: {
        source: 'task',
        title: expect.stringMatching(/^Background task failed: /),
        status: 'failed',
      },
    });
  });

  it('names the session a cross-session message came from', () => {
    expect(classify(user('x', CROSS))).toMatchObject({
      kind: 'notification',
      notification: { source: 'session', title: 'Message from nvx_folio', from: 'nvx_folio' },
      body: 'The build is green on my side.',
    });
  });

  it('shows peer messages and agent hand-backs (meta entries with an origin) instead of dropping them', () => {
    const handback = user(
      'h',
      'A report came back from an agent: <agent-message from="ag7">[from Explore] Done.</agent-message>',
      {
        is_meta: true,
        origin: {
          kind: 'peer',
          from: 'ag7',
          name: 'Explore',
          body: 'Done. **Two** files changed.',
          handback: true,
        },
      } as never,
    );
    const peer = user(
      'p',
      'A message arrived from another session: <cross-session-message from="x" from-name="nvx_folio">Hi</cross-session-message>',
      {
        is_meta: true,
        origin: { kind: 'peer', name: 'nvx_folio', body: 'Hi from folio' },
      } as never,
    );
    const { planned } = plan([handback, peer]);
    expect(planned.map((p) => [p.role, p.kind, p.notification])).toEqual([
      ['system', 'notification', { source: 'agent', title: 'Report from an agent', from: 'Explore' }],
      ['system', 'notification', { source: 'session', title: 'Message from nvx_folio', from: 'nvx_folio' }],
    ]);
    expect(text(planned[0]?.parts ?? [])).toBe('Done. **Two** files changed.');
    expect(text(planned[1]?.parts ?? [])).toBe('Hi from folio');
  });

  it('reads an agent message by its tag, and an unknown wrapper as a note from Claude Code', () => {
    expect(classify(user('a', '<agent-message from="ag2">All tests pass.</agent-message>'))).toMatchObject({
      kind: 'notification',
      notification: { source: 'agent', title: 'Report from an agent', from: 'ag2' },
      body: 'All tests pass.',
    });
    expect(classify(user('u', '<future-thing kind="x">\nSomething **new**\n</future-thing>'))).toMatchObject({
      kind: 'notification',
      notification: { source: 'system', title: 'Note from Claude Code' },
      body: 'Something **new**',
    });
  });

  it('leaves a prompt that only mentions a tag as the person wrote it', () => {
    expect(classifyUser('Why does <command-name> show up in my thread?')).toEqual({
      kind: 'prompt',
      text: 'Why does <command-name> show up in my thread?',
    });
  });
});

describe('compaction', () => {
  it('draws a divider, then the summary as a system message, and carries on after it', () => {
    const summary =
      'This session is being continued from a previous conversation that ran out of context. The summary below covers the earlier portion.\n\nSummary: ...';
    const { planned } = plan([
      user('s1', summary, { isCompactSummary: true, is_meta: true }),
      user('u2', 'Carry on'),
    ]);
    expect(planned.map((p) => [p.role, p.kind])).toEqual([
      ['system', 'compact_boundary'],
      ['system', 'compact_summary'],
      ['user', null],
    ]);
    const [div, sum, next] = planned;
    expect(div?.uuids).toEqual([]);
    expect(sum?.parent_id).toBe(div?.id);
    expect(text(sum?.parts ?? [])).toBe(summary);
    expect(next?.parent_id).toBe(sum?.id);
    // A later sync knows the summary's entry, so neither is written again.
    const again = plan(
      [user('s1', summary, { isCompactSummary: true }), user('u2', 'Carry on')],
      mirrorOf(planned),
    );
    expect(again.planned).toEqual([]);
  });

  it('knows the summary by its words when the flag is missing', () => {
    expect(
      classify(
        user('s', 'This session is being continued from a previous conversation that ran out of context.'),
      ).kind,
    ).toBe('compact');
  });
});

describe('interruptions', () => {
  it('turns "[Request interrupted by user]" into a system message', () => {
    const { planned } = plan([
      user('u1', 'Go'),
      assistant('a1', [{ type: 'text', text: 'Working' }]),
      user('i1', '[Request interrupted by user]'),
    ]);
    expect(planned.at(-1)).toMatchObject({
      role: 'system',
      kind: 'interrupted',
      parts: [{ type: 'text', text: 'Stopped by you' }],
    });
  });

  it('as a text block: alone, or beside the tool result it cut short', () => {
    const block = (uuid: string, content: unknown[]): CcSessionMessage => ({
      ...user(uuid, ''),
      message: { role: 'user', content },
    });
    const chain = [
      user('u1', 'Go'),
      assistant('a1', [{ type: 'tool_use', id: 'c1', name: 'Bash', input: {} }]),
      block('r1', [
        { type: 'tool_result', tool_use_id: 'c1', content: 'partial', is_error: true },
        { type: 'text', text: '[Request interrupted by user for tool use]' },
      ]),
      user('u2', 'Try another way'),
    ];
    const { planned } = plan(chain);
    expect(planned.map((p) => [p.role, p.kind])).toEqual([
      ['user', null],
      ['assistant', null],
      ['system', 'interrupted'],
      ['user', null],
    ]);
    expect(planned[1]?.parts.map((p) => p.type)).toEqual(['tool_call', 'tool_result']);
    expect(planned[3]?.parent_id).toBe(planned[2]?.id);
    // The next sync hangs new entries after the marker, not beside it.
    const again = plan([...chain, assistant('a2', [{ type: 'text', text: 'OK' }])], mirrorOf(planned));
    expect(again.planned).toHaveLength(1);
    expect(again.planned[0]?.parent_id).toBe(planned[3]?.id);
    expect(classify(block('i', [{ type: 'text', text: '[Request interrupted by user]' }])).kind).toBe(
      'interrupted',
    );
  });
});

describe('reminders, images and results', () => {
  it('strips <system-reminder> blocks from what the person typed, and drops a reminder-only entry', () => {
    const { planned } = plan([
      user('u1', '<system-reminder>\nThe date is today.\n</system-reminder>\nFix the bug'),
      user('u2', '<system-reminder>Only this</system-reminder>'),
    ]);
    expect(planned).toHaveLength(1);
    expect(text(planned[0]?.parts ?? [])).toBe('Fix the bug');
  });

  it('keeps a pasted screenshot as an image beside the words', () => {
    const shot: CcSessionMessage = {
      ...user('u1', ''),
      message: {
        role: 'user',
        content: [
          { type: 'image', source: { type: 'base64', media_type: 'image/png', data: 'iVBORw0KGgo=' } },
          { type: 'text', text: 'What is wrong here?' },
        ],
      },
    };
    const { planned } = plan([shot]);
    expect(planned[0]?.parts).toEqual([
      { type: 'image', url: 'data:image/png;base64,iVBORw0KGgo=', mime: 'image/png' },
      { type: 'text', text: 'What is wrong here?' },
    ]);
  });

  it('keeps tool results as strings, line-number gutter and all', () => {
    const read = '     1\u2192import x from "y";\n     2\u2192export default x;';
    const { planned } = plan([
      user('u1', 'Read it'),
      assistant('a1', [{ type: 'tool_use', id: 'c', name: 'Read', input: { file_path: 'a.ts' } }]),
      toolResult('r1', 'c', read),
    ]);
    // The fixtures' entries are a second apart: the step took as long.
    expect(planned[1]?.parts[1]).toEqual({
      type: 'tool_result',
      call_id: 'c',
      ok: true,
      result: read,
      duration_ms: 1000,
    });
  });

  it('helpers: ANSI codes and tags come out, markdown stays', () => {
    expect(stripAnsi('\u001b[31mred\u001b[0m and \u001b]8;;https://x\u0007link\u001b]8;;\u0007')).toBe(
      'red and link',
    );
    expect(bodyOf('<a><status>done</status>**bold**\n\n\n\nnext</a>')).toBe('**bold**\n\nnext');
  });
});
